export const JLPT_TOPICS = Array.from(
  new Set(JLPT_N5_WORDS.map((w) => w.topic).filter(Boolean))
).sort();

export function getRandomWords(count: number, excludeId?: string, topic?: string): JLPTWord[] {
  let pool = JLPT_N5_WORDS;
  if (topic && topic !== "All") {
    pool = pool.filter((w) => w.topic === topic);
  }
  if (excludeId) {
    pool = pool.filter((w) => w.id !== excludeId);
  }
  const shuffled = [...pool].sort(() => 0.5 - Math.random());
  return shuffled.slice(0, count);
}

export function getQuizDistractors(correctWord: JLPTWord, count: number = 3): string[] {
  const distractors = getRandomWords(count * 3, correctWord.id)
    .map((w) => w.english)
    .filter((eng) => eng.toLowerCase() !== correctWord.english.toLowerCase());
  return Array.from(new Set(distractors)).slice(0, count);
}
